import { GenkiSource } from './genki';

export const SLACK_MAX_BLOCKS = 50;
export const SLACK_MAX_SECTION_TEXT = 3000;

const CITATION = /\[(\d+(?:\s*,\s*\d+)*)\]/g;
// fenced code blocks and inline code are left as they are
const CODE = /(```[\s\S]*?(?:```|$)|`[^`\n]*`)/g;

function mapOutsideCode(text: string, fn: (prose: string) => string): string {
  return text
    .split(CODE)
    .map((part, i) => (i % 2 === 1 ? part : fn(part)))
    .join('');
}

// The source numbers an answer cites, in order of first use.
export function citedIndexes(text: string): number[] {
  const seen: number[] = [];
  mapOutsideCode(text, (prose) =>
    prose.replace(CITATION, (whole, list: string) => {
      for (const n of list.split(',').map((s) => parseInt(s.trim(), 10))) {
        if (!seen.includes(n)) seen.push(n);
      }
      return whole;
    }),
  );
  return seen;
}

// `[N]` is the source whose `index` is N, never the N-th source in the list.
export function sourceFor(sources: GenkiSource[], n: number): GenkiSource | undefined {
  return sources.find((source) => source.index === n);
}

// Turns `[N]` into a markdown link to source N when that source has a url.
export function linkCitations(text: string, sources: GenkiSource[]): string {
  return mapOutsideCode(text, (prose) =>
    prose.replace(CITATION, (whole, list: string) =>
      list
        .split(',')
        .map((s) => parseInt(s.trim(), 10))
        .map((n) => {
          const url = sourceFor(sources, n)?.url;
          return url ? `[[${n}]](${url})` : `[${n}]`;
        })
        .join(''),
    ),
  );
}

export interface SourceLink {
  title: string;
  url: string;
}

// Sources to list under the answer: the cited ones in citation order, or, when the
// answer cites nothing, the retrieved sources the platform listed. Only sources with
// a url people can open are listed, each url once.
export function sourceLinks(text: string, sources: GenkiSource[], max: number = 10): SourceLink[] {
  const cited = citedIndexes(text)
    .map((n) => sourceFor(sources, n))
    .filter((source): source is GenkiSource => !!source);
  const candidates = cited.length > 0 ? cited : sources;

  const links: SourceLink[] = [];
  for (const source of candidates) {
    if (!source.url || links.some((link) => link.url === source.url)) continue;
    links.push({ title: source.title || source.url, url: source.url });
    if (links.length >= max) break;
  }
  return links;
}

// Text inside a Slack <url|text> link may not contain these characters.
export function escapeSlackLinkText(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\|/g, '-');
}

// Small guess at the answer's language, to word the bot's own texts. genki answers
// in the question's language but does not say which one it chose.
export function looksNorwegian(text: string): boolean {
  if (/[æøåÆØÅ]/.test(text)) return true;
  const words = text.toLowerCase().match(/[a-zæøå]+/g) || [];
  const no = ['og', 'ikke', 'det', 'som', 'er', 'til', 'med', 'på', 'av', 'jeg', 'hvordan', 'kan'];
  const en = ['the', 'and', 'not', 'is', 'to', 'with', 'of', 'how', 'can', 'what', 'you', 'this'];
  const score = (list: string[]) => words.filter((word) => list.includes(word)).length;
  return score(no) > score(en);
}

export interface BotTexts {
  sourcesHeading: string;
  footer: (durationSec: number) => string;
  noAnswer: string;
  noSources: string;
  error: string;
}

export function botTexts(norwegian: boolean): BotTexts {
  if (norwegian) {
    return {
      sourcesHeading: 'Les mer:',
      footer: (sec) =>
        `Generert med KI på ${sec.toFixed(1)} sek. Svaret kan inneholde feil.\n` +
        'Gi gjerne tilbakemelding med :+1: eller :-1:, eller :stopwatch: for info om kildene.',
      noAnswer: 'Jeg fant ikke noe svar på dette i dokumentasjonen.',
      noSources: ':warning: Ingen kilder i dette svaret. Det er ikke hentet fra dokumentasjonen.',
      error: 'Beklager, noe gikk galt da jeg skulle svare. Prøv igjen om litt.',
    };
  }
  return {
    sourcesHeading: 'For more information:',
    footer: (sec) =>
      `Generated by AI in ${sec.toFixed(1)} seconds. The answer may contain mistakes.\n` +
      'Please give us your feedback with :+1: or :-1:, or :stopwatch: for more about the sources.',
    noAnswer: 'I could not find an answer to this in the documentation.',
    noSources: ':warning: No sources in this answer. It is not taken from the documentation.',
    error: 'Sorry, something went wrong while answering. Please try again in a moment.',
  };
}

export function sectionBlock(text: string): any {
  return { type: 'section', text: { type: 'mrkdwn', text } };
}

// Source links as section blocks, split so no section passes Slack's text limit.
export function sourceBlocks(links: SourceLink[], heading: string): any[] {
  if (links.length === 0) return [];
  const blocks: any[] = [];
  let current = heading;
  for (const link of links) {
    const line = `• <${link.url}|${escapeSlackLinkText(link.title)}>`;
    if (current.length + 1 + line.length > SLACK_MAX_SECTION_TEXT) {
      blocks.push(sectionBlock(current));
      current = line;
    } else {
      current += '\n' + line;
    }
  }
  blocks.push(sectionBlock(current));
  return blocks;
}

// Keeps a message within Slack's block limit: the trailing blocks (sources, footer)
// are always kept and the answer is cut short with a marker when it is too long.
export function fitBlocks(
  answerBlocks: any[],
  trailingBlocks: any[],
  max: number = SLACK_MAX_BLOCKS,
): any[] {
  const room = max - trailingBlocks.length;
  if (answerBlocks.length <= room) {
    return [...answerBlocks, ...trailingBlocks];
  }
  return [...answerBlocks.slice(0, Math.max(room - 1, 0)), sectionBlock('…'), ...trailingBlocks];
}

// The blocks under an answer: its sources, or a note that it has none, then the footer.
export function answerTrailingBlocks(
  text: string,
  sources: GenkiSource[],
  texts: BotTexts,
  durationSec: number,
  noAnswer: boolean = false,
): any[] {
  const blocks: any[] = sourceBlocks(sourceLinks(text, sources), texts.sourcesHeading);
  if (sources.length === 0 && !noAnswer) {
    // an answer from the model alone; say so rather than let it pass as documented
    blocks.push({ type: 'context', elements: [{ type: 'mrkdwn', text: texts.noSources }] });
  }
  blocks.push({ type: 'context', elements: [{ type: 'mrkdwn', text: texts.footer(durationSec) }] });
  return blocks;
}
